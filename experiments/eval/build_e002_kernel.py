"""Build the self-contained EXP-E-002 Kaggle kernel script (no Kaggle dataset needed).

Why: the private dataset upload reported success but was never listed or
attachable (API 403, "not a valid dataset source"). Instead the kernel carries
the evaluation package, frozen MMLU-Pro subset, manifest and amendments as an
embedded xz/tar payload, and downloads the four public benchmark datasets from
the Hugging Face Hub at their pinned revisions, verifying each file's SHA-256
against the manifest before use.

Output: experiments/eval/kaggle/exp-e-002-run/run_kernel.py (+ PAYLOAD.json).
Usage: build_e002_kernel.py smoke|full
"""

import base64
import hashlib
import io
import json
import sys
import tarfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUNDLE = REPO / "experiments" / "eval" / "kaggle" / "exp-e-002-bundle" / "bundle"
RUN_DIR = REPO / "experiments" / "eval" / "kaggle" / "exp-e-002-run"
# Only the English punkt_tab tables are needed (IFEval); their four hashes are pinned in the manifest.
INCLUDE = ("qwentum_eval/", "experiments/manifests/", "manifest/",
           "data_cache/nltk_data/tokenizers/punkt_tab/english/")
AMENDMENTS = ["eval-EXP-E-002-amendment-1.json", "eval-EXP-E-002-amendment-2.json", "eval-EXP-E-002-amendment-3.json", "eval-EXP-E-002-amendment-4.json"]


def main():
    mode = sys.argv[1]
    assert mode in ("smoke", "full")
    buf = io.BytesIO()
    members = {}
    with tarfile.open(fileobj=buf, mode="w:xz", preset=9) as tf:
        for p in sorted(BUNDLE.rglob("*")):
            rel = p.relative_to(BUNDLE).as_posix()
            if p.is_file() and rel.startswith(INCLUDE):
                tf.add(p, arcname=rel)
                members[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
        for a in AMENDMENTS:
            src = REPO / "experiments" / "manifests" / a
            if src.exists():
                tf.add(src, arcname=f"manifest/{a}")
                members[f"manifest/{a}"] = hashlib.sha256(src.read_bytes()).hexdigest()
    raw = buf.getvalue()
    payload_sha = hashlib.sha256(raw).hexdigest()
    entry = (RUN_DIR / "entry.py").read_text(encoding="utf-8")
    entry = entry.replace('RUN_MODE = "smoke"', f'RUN_MODE = "{mode}"', 1)
    script = (
        f'"""Generated by experiments/eval/build_e002_kernel.py. Do not edit; rebuild instead."""\n'
        f"PAYLOAD_SHA256 = {payload_sha!r}\n"
        f"PAYLOAD_MEMBERS = {json.dumps(members)}\n"
        f"PAYLOAD_B64 = {base64.b64encode(raw).decode()!r}\n\n"
        + entry
    )
    out = RUN_DIR / "run_kernel.py"
    out.write_text(script, encoding="utf-8")
    info = {"mode": mode, "payload_sha256": payload_sha, "payload_bytes": len(raw), "members": len(members),
            "entry_sha256": hashlib.sha256((RUN_DIR / 'entry.py').read_bytes()).hexdigest(),
            "run_kernel_sha256": hashlib.sha256(out.read_bytes()).hexdigest(), "run_kernel_bytes": out.stat().st_size}
    (RUN_DIR / "PAYLOAD.json").write_text(json.dumps(info, indent=1), encoding="utf-8")
    print(json.dumps(info))


if __name__ == "__main__":
    main()
